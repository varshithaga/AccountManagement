def _gst_summary_page(add: bool) -> None:
    """The new GST Summary report goes to every role that can open the Profit & Loss."""
    roles = sa.table('roles', sa.column('id', sa.Integer), sa.column('pages', sa.JSON), sa.column('is_admin', sa.Boolean))
    conn = op.get_bind()
    for role_id, pages in conn.execute(sa.select(roles.c.id, roles.c.pages).where(roles.c.is_admin.is_(False))).all():
        pages = list(pages or [])
        if add and 'profit_and_loss' in pages and 'gst_summary' not in pages:
            pages.append('gst_summary')
        elif not add and 'gst_summary' in pages:
            pages.remove('gst_summary')
        else:
            continue
        conn.execute(roles.update().where(roles.c.id == role_id).values(pages=pages))


